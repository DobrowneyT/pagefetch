#!/usr/bin/env node
//
// Point the service at a list of candidate sites and record a verdict for each.
//
//   npm run reachability                 # docs/reachability/targets.txt
//   npm run reachability -- some/list.txt
//
// DELIBERATE, and excluded from every test suite. It makes real requests to
// third parties, and running it on a schedule is the impoliteness this service
// exists to avoid. Run it when you want to know something, not to keep a
// dashboard green.
//
// Results are append-only in docs/reachability/results.jsonl. A single run is a
// snapshot; the useful artefact is the trend, because a site that starts
// blocking us is exactly what we want to notice.
import { appendFile, mkdir, readFile, writeFile } from "node:fs/promises"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..")
const OUT_DIR = join(ROOT, "docs", "reachability")
const LOG = join(OUT_DIR, "results.jsonl")
const SUMMARY = join(OUT_DIR, "RESULTS.md")

const BASE = process.env.PAGEFETCH_URL
const TOKEN = process.env.PAGEFETCH_TOKEN

if (!BASE || !TOKEN) {
  console.error("PAGEFETCH_URL and PAGEFETCH_TOKEN are both required. One without the other is unconfigured.")
  process.exit(2)
}

async function callTool(tool, args) {
  const response = await fetch(`${BASE}/fetch`, {
    method: "POST",
    headers: { "content-type": "application/json", authorization: `Bearer ${TOKEN}` },
    body: JSON.stringify({ tool, arguments: args }),
  })
  if (!response.ok) return { code: `http_${response.status}` }
  return response.json()
}

async function probe(url) {
  // The cheap probe first, exactly as consumers are told to. It costs nothing
  // and it records what we knew before asking the origin anything.
  const reachable = await callTool("check_reachable", { url })

  // max_age 0 so a run measures the site rather than our cache.
  const fetched = await callTool("fetch_page", { url, format: "text", max_age: 0 })

  return {
    at: new Date().toISOString(),
    url,
    host: new URL(url).hostname,
    probe_code: reachable.code ?? null,
    probe_robots: reachable.robots ?? null,
    probe_domain: reachable.domain ?? null,
    code: fetched.code ?? null,
    status: fetched.status ?? null,
    url_final: fetched.url_final ?? null,
    content_length: typeof fetched.content === "string" ? fetched.content.length : 0,
    detail: fetched.detail ?? null,
  }
}

function verdict(record) {
  if (record.code === "ok" && record.content_length > 0) return "reachable"
  if (record.code === "blocked_robots") return "robots policy — not a technical block"
  if (record.code === "blocked_challenge") return "refused — challenge did not clear"
  if (record.code === "domain_benched") return "benched or disabled by our own backoff"
  return record.code ?? "unknown"
}

async function renderSummary() {
  const lines = (await readFile(LOG, "utf8")).trim().split("\n").filter(Boolean)
  const records = lines.map((line) => JSON.parse(line))

  // Latest per URL, not per host. A site can allow one path and disallow
  // another, and collapsing those to one row would report whichever we happened
  // to probe last as the verdict for the whole site.
  const latest = new Map()
  const attempts = new Map()
  for (const record of records) {
    latest.set(record.url, record)
    attempts.set(record.url, (attempts.get(record.url) ?? 0) + 1)
  }

  const rows = [...latest.values()]
    .sort((a, b) => a.url.localeCompare(b.url))
    .map(
      (record) =>
        `| \`${record.url.replace(/^https?:\/\//, "")}\` | \`${record.code}\` | ${record.status ?? "—"} | ${record.content_length || "—"} | ${verdict(record)} | ${attempts.get(record.url)} | ${record.at.slice(0, 10)} |`,
    )

  const body = `# Reachability results

Generated by \`npm run reachability\`. **Do not edit by hand** — the durable
record is \`results.jsonl\`, which is append-only, and this file is rendered from
the most recent entry per URL.

A 100%-blocked host is the most useful row in the table. Nothing here is
summarised away.

| URL | Code | Status | Content | Verdict | Runs | Last checked |
|---|---|---|---|---|---|---|
${rows.join("\n")}

## Reading this

- **\`blocked_robots\` is not a failure of the build.** The site stated it does
  not want automated access, and pagefetch respects that. It will never become
  reachable, and nothing here should be bent to make it so.
- **\`blocked_challenge\` means a stock browser with a persistent profile was
  refused.** The correct response is to stop, not to escalate.
- **\`origin_error\` is the site being broken**, not the site refusing us. Those
  are different findings and the codes keep them apart.
- **Rows are per URL, not per site.** A site can allow its homepage and disallow
  every listing path — which is exactly what \`grants-search.turn2us.org.uk\`
  does — and one row per site would hide that.
`

  await writeFile(SUMMARY, body)
}

// Re-render the summary from the durable log without touching the network.
if (process.argv[2] === "--render") {
  await renderSummary()
  console.log(`Rendered ${SUMMARY} from ${LOG}`)
  process.exit(0)
}

const listPath = process.argv[2] ?? join(OUT_DIR, "targets.txt")
const targets = (await readFile(listPath, "utf8"))
  .split("\n")
  .map((line) => line.split("#")[0].trim())
  .filter(Boolean)

console.log(`Probing ${targets.length} target(s) via ${BASE}\n`)
await mkdir(OUT_DIR, { recursive: true })

for (const url of targets) {
  const record = await probe(url)
  await appendFile(LOG, `${JSON.stringify(record)}\n`)
  console.log(
    `${record.host.padEnd(34)} ${String(record.code).padEnd(18)} ${verdict(record)}` +
      (record.detail ? `\n${" ".repeat(34)} ${record.detail}` : ""),
  )
}

await renderSummary()
console.log(`\nAppended to ${LOG}`)
console.log(`Rendered ${SUMMARY}`)
